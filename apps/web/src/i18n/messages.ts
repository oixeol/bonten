const messages: Record<Locale, Record<MessageKey, string>> = {
  'pt-BR': ptBR,
  en,
};

export function isLocale(value: string): value is Locale {
  return value === 'pt-BR' || value === 'en';
}

/** Normaliza um código de idioma (ex.: "pt-BR", "en-US") para Locale. */
export function resolveLocale(tag: string | undefined | null): Locale {
  if (!tag) return 'pt-BR';
  const lower = tag.toLowerCase();
  if (lower.startsWith('pt')) return 'pt-BR';
  return 'en';
}

export function getMessages(locale: Locale): Record<MessageKey, string> {
  return messages[locale];
}

/** Detecta o locale a partir do header Accept-Language (server-safe). */
export function localeFromAcceptLanguage(header: string | null): Locale {
  if (!header) return 'pt-BR';
  const first = header.split(',')[0]?.split(';')[0]?.trim();
  return resolveLocale(first);
}

export type Translate = (key: MessageKey) => string;

export function createTranslator(locale: Locale): Translate {
  const dict = messages[locale];
  return (key) => dict[key];
}